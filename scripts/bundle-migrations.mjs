// Bundles migrations/0001..0017 (the base schema, NOT 0018 -- that one's
// FHG-specific multi-tenancy backfill; every brand-new company gets its
// own equivalent via LOCAL_CLIENT_SCHEMA_SQL in worker/tenant-db.js
// instead) into a JS module a Worker can import, since a Worker can't
// read arbitrary files off disk at runtime the way `wrangler d1 execute
// --file` can. Run this again any time a new numbered migration is
// added that a brand-new company's database should also get.
//
//   node scripts/bundle-migrations.mjs

import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const migrationsDir = path.join(root, "migrations");
const outFile = path.join(root, "worker", "migrations-bundle.js");

const EXCLUDE = new Set(["0018_multi_tenant_clients.sql"]);

const files = readdirSync(migrationsDir)
  .filter((f) => f.endsWith(".sql") && !EXCLUDE.has(f))
  .sort();

const entries = files.map((f) => {
  const sql = readFileSync(path.join(migrationsDir, f), "utf8");
  return `  // ${f}\n  ${JSON.stringify(sql)},`;
});

const output = `// AUTO-GENERATED by scripts/bundle-migrations.mjs -- do not hand-edit.
// Re-run that script after adding a new base-schema migration file.
// Bundled files: ${files.join(", ")}

export const COMPANY_MIGRATIONS = [
${entries.join("\n")}
];
`;

writeFileSync(outFile, output);
console.log(`Bundled ${files.length} migration file(s) into ${path.relative(root, outFile)}`);
